#!/usr/bin/env node
/**
 * Build-time only. Walks curated .md/.txt and writes a TS module so
 * knowledge.search never uses fs at request time (Workers-safe).
 */
import { promises as fs } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "lib/knowledge/corpus.generated.ts");
const TEXT_EXT = /\.(md|txt)$/i;

const SOURCES = [
  { dir: "knowledge/thesis", visibility: "public" },
  { dir: "knowledge/qa", visibility: "public" },
  { dir: "knowledge/documents", visibility: "confidential" },
  { dir: "knowledge/meetings", visibility: "confidential" },
  { dir: "docs/nico", visibility: "confidential" },
];

function visibilityFor(rel, fallback) {
  return fallback;
}

function titleFor(text, rel) {
  const heading = text.match(/^#\s+(.+)$/m);
  return heading ? heading[1].trim() : rel;
}

async function walk(dir, files) {
  let entries;
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    const absolute = path.join(dir, entry.name);
    if (entry.isDirectory()) await walk(absolute, files);
    else if (TEXT_EXT.test(entry.name)) files.push(absolute);
  }
}

function asTsString(value) {
  return JSON.stringify(value);
}

async function main() {
  // GitHub Actions sets CI=true. Q&A markdown is gitignored, so a sync
  // on the runner would rewrite the committed corpus without those docs
  // and fail retrieval tests. Use the generated file from git instead.
  if (process.env.CI === "true") {
    console.log("CI: skipping corpus sync; using committed corpus.generated.ts");
    return;
  }

  const docs = [];
  for (const source of SOURCES) {
    const absRoot = path.join(ROOT, source.dir);
    const files = [];
    await walk(absRoot, files);
    files.sort();
    for (const absolute of files) {
      const rel = path.relative(ROOT, absolute).split(path.sep).join("/");
      const text = await fs.readFile(absolute, "utf8");
      docs.push({
        path: rel,
        title: titleFor(text, rel),
        text,
        visibility: visibilityFor(rel, source.visibility),
      });
    }
  }

  const body = [
    "// Generated by scripts/sync-knowledge-corpus.mjs — do not edit by hand.",
    'import type { CorpusDocument } from "./corpus";',
    "",
    `export const bundledDocuments: CorpusDocument[] = ${asTsString(docs)};`,
    "",
  ].join("\n");

  await fs.mkdir(path.dirname(OUT), { recursive: true });
  await fs.writeFile(OUT, body);
  console.log(`Wrote ${docs.length} documents to ${path.relative(ROOT, OUT)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
